# ─── PDF Report Generation Routes ───────────────────────────────────────────
from flask import Blueprint, request, jsonify, session, send_file
import io
import base64
import time
from datetime import datetime

report_bp = Blueprint('report', __name__)


@report_bp.route('/api/report', methods=['POST'])
def generate_report():
    email = session.get('user')
    if not email:
        return jsonify({'success': False, 'message': 'Not authenticated'}), 401

    data = request.json
    summary = data.get('summary', {})
    insights = data.get('insights', [])
    charts_b64 = data.get('charts', [])

    try:
        from reportlab.lib.pagesizes import A4
        from reportlab.lib import colors
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib.units import inch
        from reportlab.platypus import (SimpleDocTemplate, Paragraph, Spacer,
                                        Table, TableStyle, Image as RLImage,
                                        HRFlowable, PageBreak)
        from reportlab.lib.enums import TA_CENTER, TA_LEFT

        buf = io.BytesIO()
        doc = SimpleDocTemplate(buf, pagesize=A4,
                                rightMargin=50, leftMargin=50,
                                topMargin=60, bottomMargin=50)

        styles = getSampleStyleSheet()
        story = []

        title_style = ParagraphStyle('title', fontSize=28, textColor=colors.HexColor('#6C63FF'),
                                     alignment=TA_CENTER, fontName='Helvetica-Bold', spaceAfter=6)
        sub_style = ParagraphStyle('sub', fontSize=11, textColor=colors.HexColor('#888888'),
                                   alignment=TA_CENTER, spaceAfter=20)
        h2_style = ParagraphStyle('h2', fontSize=14, textColor=colors.HexColor('#333333'),
                                  fontName='Helvetica-Bold', spaceAfter=8, spaceBefore=16)
        body_style = ParagraphStyle('body', fontSize=10, textColor=colors.HexColor('#444444'),
                                    spaceAfter=5, leading=15)
        insight_style = ParagraphStyle('insight', fontSize=10, textColor=colors.HexColor('#444444'),
                                       spaceAfter=4, leftIndent=10, leading=14)

        # Header
        story.append(Paragraph("DATALYZE", title_style))
        story.append(Paragraph("Intelligent Data Analysis Report", sub_style))
        story.append(Paragraph(f"Generated: {datetime.now().strftime('%B %d, %Y at %H:%M')} | Dataset: {summary.get('filename', 'Unknown')}", sub_style))
        story.append(HRFlowable(width="100%", thickness=2, color=colors.HexColor('#6C63FF')))
        story.append(Spacer(1, 20))

        # Summary table
        story.append(Paragraph("Dataset Overview", h2_style))
        tdata = [
            ['Metric', 'Value'],
            ['Total Rows', f"{summary.get('rows', 0):,}"],
            ['Total Columns', str(summary.get('columns', 0))],
            ['Numeric Columns', str(summary.get('numeric_cols', 0))],
            ['Categorical Columns', str(summary.get('categorical_cols', 0))],
            ['Missing Data', f"{summary.get('missing_pct', 0)}%"],
            ['Duplicate Rows', str(summary.get('duplicates', 0))],
            ['Memory Usage', f"{summary.get('memory_kb', 0)} KB"],
        ]
        t = Table(tdata, colWidths=[200, 200])
        t.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#6C63FF')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 10),
            ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.HexColor('#F9F9FF'), colors.white]),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#CCCCCC')),
            ('PADDING', (0, 0), (-1, -1), 8),
        ]))
        story.append(t)
        story.append(Spacer(1, 20))

        # Key insights
        story.append(Paragraph("Key Insights", h2_style))
        for ins in insights:
            story.append(Paragraph(f"• {ins}", insight_style))
        story.append(Spacer(1, 20))

        # Charts
        if charts_b64:
            story.append(Paragraph("Visualizations", h2_style))
            for ch in charts_b64:
                img_data = base64.b64decode(ch['img'])
                img_buf = io.BytesIO(img_data)
                rl_img = RLImage(img_buf, width=5.5 * inch, height=2.8 * inch)
                story.append(Paragraph(ch['title'], body_style))
                story.append(rl_img)
                story.append(Spacer(1, 14))

        # Footer
        story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor('#CCCCCC')))
        story.append(Spacer(1, 8))
        story.append(Paragraph("Generated by Datalyze — Intelligent Data Analysis Platform", sub_style))

        doc.build(story)
        buf.seek(0)
        fname = f"datalyze_report_{int(time.time())}.pdf"
        return send_file(buf, mimetype='application/pdf',
                         download_name=fname, as_attachment=True)
    except Exception as e:
        return jsonify({'success': False, 'message': str(e)}), 500
